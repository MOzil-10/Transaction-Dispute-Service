package com.transaction.dispute.model.dto;

import com.transaction.dispute.model.enums.DecisionRoute;
import com.transaction.dispute.model.enums.DisputeReason;
import com.transaction.dispute.model.enums.DisputeStatus;
import io.swagger.v3.oas.annotations.media.Schema;

import java.math.BigDecimal;
import java.time.OffsetDateTime;

@Schema(name = "DisputeResponse", description = "Confirmation and decision payload returned after processing a dispute submission")
public record DisputeResponseDto(

        @Schema(description = "Unique numeric sequence identifier for the dispute record", example = "5000401")
        Long disputeId,

        @Schema(description = "Human-readable unique dispute reference code", example = "DSP-77491")
        String disputeReference,

        @Schema(description = "Unique numeric identifier of the disputed transaction", example = "5000102")
        Long transactionId,

        @Schema(description = "Transaction monetary value in ZAR", example = "450.00")
        BigDecimal amount,

        @Schema(description = "Reason submitted for lodging the dispute", example = "UNAUTHORISED_MANDATE")
        DisputeReason reason,

        @Schema(description = "Calculated risk score generated by the engine (0 to 100)", example = "75")
        Integer riskScore,

        @Schema(description = "Routing outcome evaluated by the decision matrix", example = "MANUAL_INVESTIGATION")
        DecisionRoute decisionRoute,

        @Schema(description = "Current lifecycle status of the dispute", example = "QUEUED_FOR_AGENT")
        DisputeStatus status,

        @Schema(description = "User-friendly status message detailing the resolution or next steps", example = "Dispute submitted successfully and queued for back-office agent review.")
        String message,

        @Schema(description = "Timestamp when the dispute was lodged", example = "2026-10-09T12:45:00+02:00")
        OffsetDateTime createdAt
) {}